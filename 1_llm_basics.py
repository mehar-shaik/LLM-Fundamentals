import json
from openai import OpenAI
from dotenv import load_dotenv

load_dotenv() # Load environment variables from .env file
client = OpenAI() # Create an OpenAI client instance to communicate with the API

#----1.simplest possible api call ----
result=client.responses.create(
    model="gpt-4o",
    input="what is the square root of 49?"
)
#full response
print(result) #it prints whole python objects

#raw json response
print(json.dumps(result.to_dict(),indent=4)) #it prints whole json response

#just main text
print(result.output_text) #prints only output

#----2.Multi-turn conversation-->(passing a list of messages) with historical data it can give ans for our question 
result=client.responses.create(
    model="gpt-4o",
    instructions="You are a helpful assistant.",
    input=[
        {"role": "user", "content": "my name is mehar"},
        {"role":"assistant", "content": "hello mehar, how can I help you?"},
        {"role":"user","content":"what is my name?"}
    ]
)
print(result.output_text)

#----3.add system prompt , temperature , max_tokens
result=client.responses.create(
    model="gpt-4o",
    instructions="you are a helpful assistant who make jokes.",
    input="what is square of 49?",
    temperature=0.7,
    max_output_tokens=100
)
print(result.output_text)
#token usage
print(f"input token: {result.usage.input_tokens}")
print(f"output tokens: {result.usage.output_tokens}")
print(f"total tokens: {result.usage.total_tokens}")

#streaming
stream=client.responses.create(
    model="gpt-4o",
    instructions="you are a helpful assistance.",
    input="tell me a short stiry about robot.",
    stream=True
)
for event in stream:
    if hasattr(event,'delta'): #delta-> it is the new text generated by the model in this event
        print(event.delta,end="",flush=True) #flush-> it forces the output to be printed immediately without buffering